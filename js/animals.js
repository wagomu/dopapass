export function byId(id) {
  return ANIMALS.find(a => a.id === id) || ANIMALS[0];
}

export function unlockedAt(level) {
  return ANIMALS.filter(a => a.unlock <= level);
}

// from より上で to 以下のレベルで新たに解放される動物
export function newlyUnlocked(from, to) {
  return ANIMALS.filter(a => a.unlock > from && a.unlock <= to);
}

export function line(animal, kind) {
  const arr = animal[kind] || animal.idle;
  return arr[Math.floor(Math.random() * arr.length)];
}
